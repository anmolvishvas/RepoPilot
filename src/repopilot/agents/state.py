"""Immutable state schemas and data models for LangGraph multi-agent workflows."""

from __future__ import annotations

from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class MigrationPhase(StrEnum):
    """Phases of the LangGraph migration execution lifecycle."""

    INITIALIZE = "initialize"
    PLANNING = "planning"
    SYNTHESIZING = "synthesizing"
    SANDBOX_TESTING = "sandbox_testing"
    REFLECTING = "reflecting"
    HUMAN_REVIEW = "human_review"
    VERIFIED = "verified"
    FAILED = "failed"
    ESCALATED = "escalated"


class ToolExecutionTrace(BaseModel):
    """Audit trace of an individual tool invocation."""

    model_config = ConfigDict(strict=True, frozen=True)

    tool_name: str = Field(min_length=1)
    args: dict[str, Any] = Field(default_factory=dict)
    execution_time_ms: float = Field(ge=0.0)
    success: bool
    output_summary: str = Field(default="")


class DiffHunk(BaseModel):
    """Synthesized unified diff targeting a specific file."""

    model_config = ConfigDict(strict=True, frozen=True)

    file_path: str = Field(min_length=1)
    diff_text: str = Field(min_length=1)
    target_symbol: str | None = None
    explanation: str | None = None


class FailedAssertion(BaseModel):
    """Detailed metadata for a failed test assertion captured in the sandbox."""

    model_config = ConfigDict(strict=True, frozen=True)

    test_name: str = Field(min_length=1)
    file_path: str = Field(min_length=1)
    line_number: int | None = Field(default=None, ge=1)
    assertion_message: str = Field(default="")
    stack_trace: str = Field(default="")


class SandboxTestResult(BaseModel):
    """Outcome of running test suites in the ephemeral Docker container."""

    model_config = ConfigDict(strict=True, frozen=True)

    exit_code: int
    stdout: str = Field(default="")
    stderr: str = Field(default="")
    total_tests: int = Field(ge=0, default=0)
    passed_tests: int = Field(ge=0, default=0)
    failed_tests: int = Field(ge=0, default=0)
    failures: list[FailedAssertion] = Field(default_factory=list)
    execution_time_seconds: float = Field(ge=0.0, default=0.0)

    @property
    def passed(self) -> bool:
        """Return True if the test suite succeeded with zero exit code."""
        return self.exit_code == 0 and self.failed_tests == 0


class ReflectionFeedback(BaseModel):
    """Guidance synthesized by the Critic agent during self-healing cycles."""

    model_config = ConfigDict(strict=True, frozen=True)

    iteration: int = Field(ge=1)
    root_cause_analysis: str = Field(min_length=1)
    suggested_patch_adjustments: list[str] = Field(default_factory=list)
    target_files_to_remediate: list[str] = Field(default_factory=list)


class MigrationPlanStep(BaseModel):
    """Atomic step in a multi-file migration execution plan."""

    model_config = ConfigDict(strict=True, frozen=True)

    step_number: int = Field(ge=1)
    file_path: str = Field(min_length=1)
    target_symbol_ids: list[str] = Field(default_factory=list)
    transformation_description: str = Field(min_length=1)
    dependencies: list[int] = Field(default_factory=list)


class MigrationPlan(BaseModel):
    """Overall execution plan generated by the Planner Agent."""

    model_config = ConfigDict(strict=True, frozen=True)

    recipe: str = Field(min_length=1)
    steps: list[MigrationPlanStep] = Field(default_factory=list)
    affected_files: list[str] = Field(default_factory=list)


class MigrationState(BaseModel):
    """Root immutable state managed by the LangGraph state machine."""

    model_config = ConfigDict(strict=True, frozen=True)

    task_id: str = Field(min_length=1)
    repo_path: str = Field(min_length=1)
    recipe: str = Field(min_length=1)
    phase: MigrationPhase = MigrationPhase.INITIALIZE
    plan: MigrationPlan | None = None
    patches: list[DiffHunk] = Field(default_factory=list)
    latest_sandbox_result: SandboxTestResult | None = None
    reflections: list[ReflectionFeedback] = Field(default_factory=list)
    tool_traces: list[ToolExecutionTrace] = Field(default_factory=list)
    retry_count: int = Field(default=0, ge=0)
    max_retries: int = Field(default=3, ge=1)
    error_message: str | None = None
    is_terminal: bool = False
